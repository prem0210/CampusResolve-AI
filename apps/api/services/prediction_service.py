from __future__ import annotations

import json
import logging
import math
from pathlib import Path
from typing import Any

import faiss
import joblib
import numpy as np
import pandas as pd
from sentence_transformers import SentenceTransformer

from src.explainability.explain_predictions import (
    explain_category_prediction,
    explain_priority_prediction,
    generate_human_readable_explanation,
)


logger = logging.getLogger(__name__)

PROJECT_ROOT = Path(__file__).resolve().parents[3]
ARTIFACTS_DIR = PROJECT_ROOT / "artifacts"

CATEGORY_MODEL_PATH = (
    ARTIFACTS_DIR / "category_model" / "category_classifier.joblib"
)
PRIORITY_MODEL_PATH = (
    ARTIFACTS_DIR / "priority_model" / "priority_classifier.joblib"
)
RESOLUTION_MODEL_PATH = (
    ARTIFACTS_DIR
    / "resolution_model"
    / "resolution_time_regressor.joblib"
)
RESOLUTION_METRICS_PATH = (
    ARTIFACTS_DIR / "resolution_model" / "metrics.json"
)

FAISS_INDEX_PATH = ARTIFACTS_DIR / "faiss_index" / "complaints.index"
FAISS_METADATA_PATH = (
    ARTIFACTS_DIR / "faiss_index" / "complaint_metadata.csv"
)
FAISS_CONFIG_PATH = (
    ARTIFACTS_DIR
    / "faiss_index"
    / "duplicate_detection_config.json"
)

TOP_K = 5

REQUIRED_PAYLOAD_FIELDS = {
    "complaint_text",
    "affected_population",
    "safety_flag",
    "repeat_count",
    "location_type",
    "language",
}

DEPARTMENT_MAPPING = {
    "Electrical and Power": "Electrical Maintenance",
    "Water and Plumbing": "Plumbing and Civil Maintenance",
    "Hostel and Accommodation": "Hostel Administration",
    "Wi-Fi and IT Services": "IT Support and Network Cell",
    "Classroom and Laboratory": "Academic Infrastructure",
    "Cleanliness and Waste": "Housekeeping and Sanitation",
    "Safety and Security": "Security Office",
    "Transport and Parking": "Transport Cell",
    "Administration and Documents": "Administrative Office",
    "Food and Canteen": "Canteen Committee",
}


class PredictionService:
    def __init__(self) -> None:
        self.category_model: Any | None = None
        self.priority_model: Any | None = None
        self.resolution_model: Any | None = None
        self.embedding_model: SentenceTransformer | None = None
        self.faiss_index: faiss.Index | None = None
        self.faiss_metadata: pd.DataFrame | None = None
        self.duplicate_threshold = 0.75
        self.resolution_interval = 24.0
        self.load_error: str | None = None

    def load_artifacts(self) -> None:
        artifact_paths = [
            CATEGORY_MODEL_PATH,
            PRIORITY_MODEL_PATH,
            RESOLUTION_MODEL_PATH,
            RESOLUTION_METRICS_PATH,
            FAISS_INDEX_PATH,
            FAISS_METADATA_PATH,
            FAISS_CONFIG_PATH,
        ]

        missing_paths = [
            str(path)
            for path in artifact_paths
            if not path.is_file()
        ]

        if missing_paths:
            self.load_error = (
                "Required model artifacts are missing: "
                + ", ".join(missing_paths)
            )
            raise FileNotFoundError(self.load_error)

        try:
            # Load only artifacts generated by your controlled training pipeline.
            self.category_model = joblib.load(CATEGORY_MODEL_PATH)
            self.priority_model = joblib.load(PRIORITY_MODEL_PATH)
            self.resolution_model = joblib.load(RESOLUTION_MODEL_PATH)

            resolution_metrics = json.loads(
                RESOLUTION_METRICS_PATH.read_text(encoding="utf-8")
            )
            prediction_interval = resolution_metrics.get(
                "prediction_interval",
                {},
            )
            self.resolution_interval = max(
                0.0,
                float(prediction_interval["plus_minus_hours"]),
            )

            faiss_config = json.loads(
                FAISS_CONFIG_PATH.read_text(encoding="utf-8")
            )
            self.duplicate_threshold = float(
                faiss_config["metrics"]["selected_threshold"]
            )

            if not 0.0 <= self.duplicate_threshold <= 1.0:
                raise ValueError(
                    "Duplicate threshold must be between 0 and 1."
                )

            model_name = str(faiss_config["model_name"]).strip()
            if not model_name:
                raise ValueError(
                    "Duplicate-detection model name is empty."
                )

            self.embedding_model = SentenceTransformer(model_name)
            self.faiss_index = faiss.read_index(str(FAISS_INDEX_PATH))
            self.faiss_metadata = pd.read_csv(
                FAISS_METADATA_PATH
            ).fillna("")

            required_metadata_columns = {
                "complaint_id",
                "complaint_text",
                "category",
                "priority",
            }
            missing_columns = (
                required_metadata_columns
                - set(self.faiss_metadata.columns)
            )

            if missing_columns:
                missing_text = ", ".join(sorted(missing_columns))
                raise ValueError(
                    f"FAISS metadata is missing columns: {missing_text}"
                )

            if self.faiss_index.ntotal != len(self.faiss_metadata):
                raise ValueError(
                    "FAISS index and metadata row count do not match: "
                    f"{self.faiss_index.ntotal} index vectors, "
                    f"{len(self.faiss_metadata)} metadata rows."
                )

            self.load_error = None

        except Exception as exc:
            self._clear_artifacts()
            self.load_error = (
                f"Unable to load prediction artifacts: {exc}"
            )
            logger.exception("Prediction artifact loading failed.")
            raise RuntimeError(self.load_error) from exc

    def _clear_artifacts(self) -> None:
        self.category_model = None
        self.priority_model = None
        self.resolution_model = None
        self.embedding_model = None
        self.faiss_index = None
        self.faiss_metadata = None

    def is_ready(self) -> bool:
        return all(
            (
                self.category_model is not None,
                self.priority_model is not None,
                self.resolution_model is not None,
                self.embedding_model is not None,
                self.faiss_index is not None,
                self.faiss_metadata is not None,
            )
        )

    def _validate_payload(
        self,
        payload: dict[str, Any],
    ) -> dict[str, Any]:
        missing_fields = REQUIRED_PAYLOAD_FIELDS - set(payload)

        if missing_fields:
            field_list = ", ".join(sorted(missing_fields))
            raise ValueError(
                f"Prediction payload is missing required fields: {field_list}"
            )

        complaint_text = str(payload["complaint_text"]).strip()
        if not complaint_text:
            raise ValueError("Complaint text cannot be empty.")

        affected_population = int(payload["affected_population"])
        repeat_count = int(payload["repeat_count"])

        if affected_population < 0:
            raise ValueError(
                "Affected population cannot be negative."
            )

        if repeat_count < 0:
            raise ValueError("Repeat count cannot be negative.")

        location_type = str(payload["location_type"]).strip()
        language = str(payload["language"]).strip()

        if not location_type:
            raise ValueError("Location type cannot be empty.")

        if not language:
            raise ValueError("Language cannot be empty.")

        return {
            "complaint_text": complaint_text,
            "affected_population": affected_population,
            "safety_flag": bool(payload["safety_flag"]),
            "repeat_count": repeat_count,
            "location_type": location_type,
            "language": language,
        }

    def _search_duplicates(
        self,
        complaint_text: str,
    ) -> list[dict[str, Any]]:
        if (
            self.embedding_model is None
            or self.faiss_index is None
            or self.faiss_metadata is None
        ):
            raise RuntimeError(
                "Duplicate-detection artifacts are not loaded."
            )

        embedding = self.embedding_model.encode(
            [complaint_text],
            convert_to_numpy=True,
            normalize_embeddings=True,
        ).astype(np.float32)

        scores, indices = self.faiss_index.search(embedding, TOP_K)
        candidates: list[dict[str, Any]] = []

        for score, index_position in zip(scores[0], indices[0]):
            position = int(index_position)

            if position < 0 or position >= len(self.faiss_metadata):
                continue

            similarity_score = float(score)

            if not math.isfinite(similarity_score):
                continue

            row = self.faiss_metadata.iloc[position]

            candidates.append(
                {
                    "complaint_id": str(row["complaint_id"]),
                    "complaint_text": str(row["complaint_text"]),
                    "category": str(row["category"]),
                    "priority": str(row["priority"]),
                    "similarity_score": round(similarity_score, 4),
                }
            )

        return candidates

    def _build_explanations(
        self,
        complaint_text: str,
        priority_features: dict[str, Any],
    ) -> tuple[Any | None, Any | None, str | None]:
        try:
            category_explanation = explain_category_prediction(
                self.category_model,
                complaint_text,
            )
            priority_explanation = explain_priority_prediction(
                self.priority_model,
                priority_features,
            )
            explanation = generate_human_readable_explanation(
                category_explanation,
                priority_explanation,
            )

            return (
                category_explanation,
                priority_explanation,
                explanation,
            )

        except Exception:
            logger.exception(
                "Prediction generated, but explainability generation failed."
            )
            return None, None, None

    def predict(self, payload: dict[str, Any]) -> dict[str, Any]:
        if not self.is_ready():
            detail = self.load_error or (
                "Prediction service artifacts are not loaded."
            )
            raise RuntimeError(detail)

        validated_payload = self._validate_payload(payload)
        complaint_text = validated_payload["complaint_text"]

        category = str(
            self.category_model.predict([complaint_text])[0]
        ).strip()

        if category not in DEPARTMENT_MAPPING:
            raise RuntimeError(
                "Category model returned an unsupported category: "
                f"{category!r}"
            )

        category_probabilities = self.category_model.predict_proba(
            [complaint_text]
        )[0]
        category_confidence = float(np.max(category_probabilities))

        department = DEPARTMENT_MAPPING[category]

        priority_features = {
            "affected_population": validated_payload[
                "affected_population"
            ],
            "safety_flag": validated_payload["safety_flag"],
            "repeat_count": validated_payload["repeat_count"],
            "category": category,
            "location_type": validated_payload["location_type"],
            "language": validated_payload["language"],
        }

        priority_frame = pd.DataFrame([priority_features])

        priority = str(
            self.priority_model.predict(priority_frame)[0]
        ).strip()

        priority_probabilities = self.priority_model.predict_proba(
            priority_frame
        )[0]
        priority_confidence = float(np.max(priority_probabilities))

        resolution_features = {
            **priority_features,
            "priority": priority,
        }

        resolution_frame = pd.DataFrame([resolution_features])
        estimated_resolution_hours = float(
            self.resolution_model.predict(resolution_frame)[0]
        )

        if not math.isfinite(estimated_resolution_hours):
            raise RuntimeError(
                "Resolution model returned a non-finite prediction."
            )

        estimated_resolution_hours = max(
            0.0,
            estimated_resolution_hours,
        )

        duplicate_candidates = self._search_duplicates(complaint_text)
        possible_duplicate = bool(
            duplicate_candidates
            and duplicate_candidates[0]["similarity_score"]
            >= self.duplicate_threshold
        )

        (
            category_explanation,
            priority_explanation,
            explanation,
        ) = self._build_explanations(
            complaint_text=complaint_text,
            priority_features=priority_features,
        )

        return {
            "predicted_category": category,
            "category_confidence": round(category_confidence, 4),
            "assigned_department": department,
            "predicted_priority": priority,
            "priority_confidence": round(priority_confidence, 4),
            "estimated_resolution_hours": round(
                estimated_resolution_hours,
                2,
            ),
            "prediction_interval_plus_minus_hours": round(
                self.resolution_interval,
                2,
            ),
            "duplicate_threshold": round(
                self.duplicate_threshold,
                4,
            ),
            "possible_duplicate": possible_duplicate,
            "duplicate_candidates": duplicate_candidates,
            "category_explanation": category_explanation,
            "priority_explanation": priority_explanation,
            "explanation": explanation,
        }